package npmtree

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func workspace(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// yarn v1: each entry's key lists the ranges dependents asked for, and each
// entry lists its own dependencies with ranges, so a hold names its parent.
// The shape is yarn's own (facebook/react's yarn.lock).
const yarnHeld = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


vscode-languageclient@^10.1.2:
  version "10.1.2"
  resolved "https://registry.yarnpkg.com/vscode-languageclient/-/vscode-languageclient-10.1.2.tgz#abc"
  integrity sha512-x
  dependencies:
    minimatch "^10.2.6"
    semver "^7.6.0"

minimatch@^10.2.6:
  version "10.2.6"
  resolved "https://registry.yarnpkg.com/minimatch/-/minimatch-10.2.6.tgz#def"
  integrity sha512-y

semver@^7.6.0:
  version "7.6.3"
`

func TestYarnV1HoldNamesTheParent(t *testing.T) {
	dir := workspace(t, map[string]string{
		"package.json": `{"dependencies":{"vscode-languageclient":"^10.1.2"}}`,
		"yarn.lock":    yarnHeld,
	})
	r := ReachOf(dir, "minimatch", "11.0.1")
	if !r.Held() || !strings.Contains(r.HoldList(), "vscode-languageclient@10.1.2 requires minimatch ^10.2.6") {
		t.Fatalf("reach %+v", r)
	}
	if got := OverrideEntry(r.Tool, "minimatch", "11.0.1"); got != `"resolutions": { "minimatch": "11.0.1" }` {
		t.Errorf("yarn's forcing entry: %s", got)
	}
	if r := ReachOf(dir, "semver", "7.6.4"); !r.Movable() {
		t.Errorf("semver 7.6.4 is within ^7.6.0: %+v", r)
	}
	below, err := Below(dir, "minimatch", "11.0.1")
	if err != nil || len(below) != 1 || !strings.Contains(below[0], "10.2.6") {
		t.Errorf("Below = %v, %v", below, err)
	}
}

// Two ranges of one package resolving to two versions: only the range that
// resolved below the fix, and only its requester, is a hold.
func TestYarnV1OnlyTheCopyBelowTheFixCounts(t *testing.T) {
	lock := `# yarn lockfile v1


a@^1.0.0:
  version "1.0.0"
  dependencies:
    qs "6.13.0"

b@^1.0.0:
  version "1.0.0"
  dependencies:
    qs "^6.11.0"

qs@6.13.0:
  version "6.13.0"

qs@^6.11.0:
  version "6.16.0"
`
	dir := workspace(t, map[string]string{"package.json": `{"dependencies":{"a":"^1.0.0","b":"^1.0.0"}}`, "yarn.lock": lock})
	r := ReachOf(dir, "qs", "6.16.0")
	if !r.Held() || r.HoldList() != "a@1.0.0 requires qs 6.13.0" {
		t.Fatalf("holds %q", r.HoldList())
	}
}

// bun.lock (text, JSONC): entries are [ident, registry, metadata, integrity],
// nested keys are a dependent's own copy, and trailing commas are allowed.
// The shape is bun's own (oven-sh/bun's bun.lock).
const bunHeld = `{
  "lockfileVersion": 1,
  "workspaces": {
    "": {
      "name": "app",
      "dependencies": {
        "vscode-languageclient": "^10.1.2",
        "glob": "^12.0.0",
      },
    },
  },
  "packages": {
    "glob": ["glob@12.0.0", "", { "dependencies": { "minimatch": "^10.2.6 || ^11.0.0" } }, "sha512-a"],

    "minimatch": ["minimatch@11.0.1", "", {}, "sha512-b"],

    "vscode-languageclient": ["vscode-languageclient@10.1.2", "", { "dependencies": { "minimatch": "^10.2.6" } }, "sha512-c"],

    "vscode-languageclient/minimatch": ["minimatch@10.2.6", "", {}, "sha512-d"],
  }
}
`

func TestBunLockHoldFollowsNestedCopies(t *testing.T) {
	dir := workspace(t, map[string]string{"package.json": `{"dependencies":{"vscode-languageclient":"^10.1.2","glob":"^12.0.0"}}`, "bun.lock": bunHeld})
	r := ReachOf(dir, "minimatch", "11.0.1")
	if !r.Held() || r.HoldList() != "vscode-languageclient@10.1.2 requires minimatch ^10.2.6" {
		t.Fatalf("reach %+v (glob's copy is already fixed and must not count)", r)
	}
	below, err := Below(dir, "minimatch", "11.0.1")
	if err != nil || len(below) != 1 || !strings.Contains(below[0], "vscode-languageclient/minimatch@10.2.6") {
		t.Errorf("Below = %v, %v", below, err)
	}
}

// pnpm-lock.yaml records the version a dependent resolved, never the range it
// allows, so a hold cannot be established from it, and Reach says why rather
// than guess. Its resolved versions are still read, so apply can check where
// an update landed. The shape is pnpm 9's own (vuejs/core's pnpm-lock.yaml).
const pnpmLock = `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      vscode-languageclient:
        specifier: ^10.1.2
        version: 10.1.2

packages:

  minimatch@10.2.6:
    resolution: {integrity: sha512-y}

  '@scope/thing@1.0.0':
    resolution: {integrity: sha512-z}

  vscode-languageclient@10.1.2:
    resolution: {integrity: sha512-x}

snapshots:

  minimatch@10.2.6: {}

  vscode-languageclient@10.1.2:
    dependencies:
      minimatch: 10.2.6
`

func TestPnpmReachIsNotEstablishedAndSaysWhy(t *testing.T) {
	dir := workspace(t, map[string]string{"package.json": `{"dependencies":{"vscode-languageclient":"^10.1.2"}}`, "pnpm-lock.yaml": pnpmLock})
	r := ReachOf(dir, "minimatch", "11.0.1")
	if r.Established || !strings.Contains(r.Why, "resolved") {
		t.Fatalf("reach %+v; want not established, saying pnpm records resolved versions", r)
	}
	below, err := Below(dir, "minimatch", "11.0.1")
	if err != nil || len(below) != 1 || !strings.Contains(below[0], "10.2.6") {
		t.Errorf("Below = %v, %v", below, err)
	}
	if below, _ := Below(dir, "@scope/thing", "1.0.0"); len(below) != 0 {
		t.Errorf("a scoped package at the fix reported below: %v", below)
	}
}

// Lockfiles nox does not read say so: yarn berry and bun's binary lockfile.
func TestUnreadLockfilesSayWhy(t *testing.T) {
	for name, files := range map[string]map[string]string{
		"yarn berry": {"yarn.lock": "__metadata:\n  version: 8\n\n\"minimatch@npm:^10.2.6\":\n  version: 10.2.6\n"},
		"bun binary": {"bun.lockb": "\x00binary"},
	} {
		dir := workspace(t, files)
		if r := ReachOf(dir, "minimatch", "11.0.1"); r.Established || r.Why == "" {
			t.Errorf("%s: reach %+v; want not established with a reason", name, r)
		}
	}
}

// A lockfile with no copy of the package establishes nothing about it: an
// empty graph has no holds, and "no holds" must not read as "free to move".
func TestNoCopyInTheLockfileIsNotEstablished(t *testing.T) {
	for name, files := range map[string]map[string]string{
		"empty yarn v1":  {"yarn.lock": "# yarn lockfile v1\n"},
		"npm without it": {"package-lock.json": `{"lockfileVersion":3,"packages":{"":{},"node_modules/other":{"version":"1.0.0"}}}`},
	} {
		if r := ReachOf(workspace(t, files), "qs", "6.16.0"); r.Established || !strings.Contains(r.Why, "no copy of qs") {
			t.Errorf("%s: %+v", name, r)
		}
	}
}
