package iso27001

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// statusLabel is the plain-language heading for a status.
func statusLabel(s Status) string {
	switch s {
	case SupportingEvidence:
		return "Supporting evidence"
	case OpenIssues:
		return "Open issues"
	case LimitedEvidence:
		return "Limited evidence"
	}
	return "No technical evidence"
}

// JSON renders the assessment as indented JSON with a trailing newline. The
// output depends only on a, so the same evidence gives the same bytes.
func (a Assessment) JSON() ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(a); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// Terminal renders the short terminal summary: what nox can evidence, what is
// weak, and what needs organizational evidence.
func (a Assessment) Terminal() string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s: technical evidence from your security scan\n\n", Standard)
	b.WriteString(ShortNotice + "\n\n")
	p := a.Provenance
	fmt.Fprintf(&b, "Based on a scan by nox %s on %s", p.ScanToolVersion, p.ScanGeneratedAt)
	if p.Commit != "" {
		fmt.Fprintf(&b, ", repository at %s", shortCommit(p.Commit))
	}
	b.WriteString(".\nEvidence read: ")
	names := make([]string, len(p.Artifacts))
	for i, art := range p.Artifacts {
		names[i] = art.Name
	}
	b.WriteString(strings.Join(names, ", ") + "\n")
	if len(p.ScopesNotScanned) > 0 {
		fmt.Fprintf(&b, "Not scanned: %s. Controls that depend on them have no evidence from this scan.\n", strings.Join(p.ScopesNotScanned, ", "))
	}
	b.WriteString("\n")
	for _, st := range []Status{SupportingEvidence, OpenIssues, LimitedEvidence, NotEvidenced} {
		writeGroup(&b, a, st)
	}
	fmt.Fprintf(&b, "Organizational evidence you still need: %d items (policies, risk assessment, access reviews, incident records, supplier agreements and more).\n", len(a.Organizational))
	b.WriteString("The checklist, with the evidence behind every claim above, is in the written report.\n")
	return b.String()
}

var groupIntro = map[Status]string{
	SupportingEvidence: "Nox can evidence these (checks ran, nothing open):",
	OpenIssues:         "Evidence exists, but issues are open:",
	LimitedEvidence:    "Nox sees only part of these:",
	NotEvidenced:       "Nox has no technical evidence for these:",
}

func writeGroup(b *strings.Builder, a Assessment, st Status) {
	var rows []string
	for _, c := range a.Controls {
		if c.Status != st {
			continue
		}
		row := fmt.Sprintf("  %s %s", c.ID, c.Title)
		if note := headline(c); note != "" {
			row += " (" + note + ")"
		}
		rows = append(rows, row)
	}
	if len(rows) == 0 {
		return
	}
	fmt.Fprintf(b, "%s\n%s\n\n", groupIntro[st], strings.Join(rows, "\n"))
}

// headline is the one-clause reason shown beside a control in the summary.
func headline(c Control) string {
	switch c.Status {
	case OpenIssues:
		n := 0
		for _, e := range c.Evidence {
			n += e.Findings
		}
		return fmt.Sprintf("%d open finding(s)", n)
	case LimitedEvidence:
		if len(c.Gaps) > 0 {
			return "see gaps"
		}
		return "indirect evidence"
	}
	return ""
}

func shortCommit(c string) string {
	if len(c) > 12 {
		return c[:12]
	}
	return c
}

// Markdown renders the reviewer-facing report.
func (a Assessment) Markdown() string {
	var b strings.Builder
	p := a.Provenance
	fmt.Fprintf(&b, "# %s: technical evidence from a nox scan\n\n", Standard)
	fmt.Fprintf(&b, "> %s\n\n", Notice)

	b.WriteString("## Provenance\n\n")
	fmt.Fprintf(&b, "- Assessment generated by nox %s\n", a.Meta.ToolVersion)
	fmt.Fprintf(&b, "- Scan run by nox %s on %s (offline: %t)\n", p.ScanToolVersion, p.ScanGeneratedAt, p.ScanOffline)
	if p.Commit != "" {
		fmt.Fprintf(&b, "- Repository revision when this was generated: %s (the scan may have run at an earlier revision)\n", p.Commit)
	}
	fmt.Fprintf(&b, "- Scopes scanned: %s\n", strings.Join(p.ScopesScanned, ", "))
	if len(p.ScopesNotScanned) > 0 {
		fmt.Fprintf(&b, "- Scopes not scanned: %s\n", strings.Join(p.ScopesNotScanned, ", "))
	}
	fmt.Fprintf(&b, "- Scan degradations recorded: %d\n", p.Degradations)
	b.WriteString("- Evidence files (SHA-256 identifies the exact bytes relied on):\n")
	for _, art := range p.Artifacts {
		fmt.Fprintf(&b, "  - `%s` (%s) `%s`\n", art.Name, art.Kind, art.SHA256)
	}

	b.WriteString("\n## Summary\n\n")
	s := a.Overview()
	fmt.Fprintf(&b, "%s\n\n", s)
	b.WriteString("| Control | Title | Evidence status |\n|---|---|---|\n")
	for _, c := range a.Controls {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", c.ID, c.Title, statusLabel(c.Status))
	}

	b.WriteString("\n## Controls\n")
	for _, c := range a.Controls {
		writeControlMarkdown(&b, c)
	}

	b.WriteString("\n## Organizational evidence required\n\n")
	b.WriteString("A repository cannot show any of the following. A reviewer will ask for each; none is produced by a scan.\n\n")
	for _, it := range a.Organizational {
		fmt.Fprintf(&b, "- [ ] **%s** (%s): %s", it.Title, it.Reference, it.Needed)
		if len(it.Controls) > 0 {
			fmt.Fprintf(&b, " Needed for: %s.", strings.Join(it.Controls, ", "))
		}
		b.WriteString("\n")
	}
	return b.String()
}

// Overview is the one-paragraph count shown at the top of the report.
func (a Assessment) Overview() string {
	s := a.Summary
	return fmt.Sprintf("Of the %d Annex A controls nox maps: supporting evidence %d, open issues %d, limited evidence %d, no technical evidence %d.",
		s.Controls, s.SupportingEvidence, s.OpenIssues, s.LimitedEvidence, s.NotEvidenced)
}

func writeControlMarkdown(b *strings.Builder, c Control) {
	fmt.Fprintf(b, "\n### %s %s\n\n", c.ID, c.Title)
	fmt.Fprintf(b, "Evidence status: **%s**\n\n", statusLabel(c.Status))
	if len(c.Evidence) > 0 {
		b.WriteString("What the scan shows:\n\n")
		for _, e := range c.Evidence {
			fmt.Fprintf(b, "- %s (source: `%s`)", e.Statement, e.Artifact)
			if len(e.Rules) > 0 {
				fmt.Fprintf(b, " Rules: %s.", strings.Join(e.Rules, ", "))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	if len(c.Gaps) > 0 {
		b.WriteString("Gaps in this run:\n\n")
		for _, g := range c.Gaps {
			fmt.Fprintf(b, "- %s\n", g)
		}
		b.WriteString("\n")
	}
	b.WriteString("What this evidence cannot show:\n\n")
	for _, l := range c.Limits {
		fmt.Fprintf(b, "- %s\n", l)
	}
	if len(c.Organizational) > 0 {
		fmt.Fprintf(b, "\nOrganizational evidence to prepare: %s.\n", strings.Join(c.Organizational, ", "))
	}
}
