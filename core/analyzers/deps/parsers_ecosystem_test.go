// TestParsePoetryLock_IgnoresNestedTables guards the specific trap in this
// format: [package.dependencies] and [metadata] sit between [[package]] blocks
// and carry their own keys. Treating any `name =` or `version =` as a package
// field pulls in the lock-version from [metadata].
func TestParsePoetryLock_IgnoresNestedTables(t *testing.T) {
	t.Parallel()

	pkgs, err := parsePoetryLock([]byte(poetryLock))
	if err != nil {
		t.Fatalf("parsePoetryLock: %v", err)
	}
	if len(pkgs) != 2 {
		t.Fatalf("expected exactly 2 packages, got %d: %+v", len(pkgs), pkgs)
	}
	for _, p := range pkgs {
		if p.Version == "2.0" {
			t.Errorf("the [metadata] lock-version was parsed as a package: %+v", p)
		}
	}
}

// --- shared behaviour ---

// TestEcosystemParsers_EmptyAndMalformed pins that a lockfile which is present
// but yields nothing is not an error. An empty result flows to the caller,
// which reports it as a degradation; returning an error here would abort the
// whole scan on a file we simply could not read anything from.
func TestEcosystemParsers_EmptyAndMalformed(t *testing.T) {
	t.Parallel()

	for name, parse := range map[string]func([]byte) ([]Package, error){
		"yarn":   parseYarnLock,
		"pnpm":   parsePnpmLock,
		"poetry": parsePoetryLock,
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			for _, input := range []string{"", "\n\n", "not a lockfile at all", "{ json: true }"} {
				if _, err := parse([]byte(input)); err != nil {
					t.Errorf("input %q returned an error; empty results are expected instead: %v", input, err)
				}
			}
		})
	}
}

func assertPackages(t *testing.T, got []Package, want map[string]string, ecosystem string) {
	t.Helper()

	found := make(map[string]string, len(got))
	for _, p := range got {
		found[p.Name] = p.Version
		if p.Ecosystem != ecosystem {
			t.Errorf("%s: ecosystem = %q, want %q", p.Name, p.Ecosystem, ecosystem)
		}
	}

	for name, version := range want {
		gotVersion, ok := found[name]
		if !ok {
			t.Errorf("%s was not parsed (got %v)", name, found)
			continue
		}
		if gotVersion != version {
			t.Errorf("%s: version = %q, want %q", name, gotVersion, version)
		}
	}
}

// --- formats and shapes found by adversarial review ---

// pnpm 9 dropped the leading slash from package keys and moved resolution data
// into a `snapshots:` section. It has been the default since 2024, so a parser
// handling only v5 and v6 leaves most current pnpm projects unscanned — the
// silent blind spot these parsers exist to remove.
const pnpmLockV9 = `lockfileVersion: '9.0'

settings:
  autoInstallPeers: true

importers:

  .:
    dependencies:
      lodash:
        specifier: ^4.17.21
        version: 4.17.21

packages:

  lodash@4.17.21:
    resolution: {integrity: sha512-abc==}

  '@babel/core@7.22.5':
    resolution: {integrity: sha512-def==}

  react-dom@18.2.0:
    resolution: {integrity: sha512-ghi==}
    peerDependencies:
      react: ^18.2.0

snapshots:

  lodash@4.17.21: {}
`

func TestParsePnpmLock_V9(t *testing.T) {
	t.Parallel()

	pkgs, err := parsePnpmLock([]byte(pnpmLockV9))
	if err != nil {
		t.Fatalf("parsePnpmLock: %v", err)
	}
	assertPackages(t, pkgs, map[string]string{
		"lodash":      "4.17.21",
		"@babel/core": "7.22.5",
		"react-dom":   "18.2.0",
	}, "npm")
}

// TestParsePnpmLock_PeerSuffixes covers both spellings of the peer-dependency
// suffix. v5 appends "_peer@version" and v6+ uses "(peer@version)"; leaving
// either attached corrupts both the name and the version, so no advisory can
// ever match.
func TestParsePnpmLock_PeerSuffixes(t *testing.T) {
	t.Parallel()

	for _, tc := range []struct{ name, input, wantName, wantVersion string }{
		{"v5 underscore", "lockfileVersion: 5.4\n\npackages:\n\n  /react-dom/16.8.0_react@16.8.0:\n    dev: false\n", "react-dom", "16.8.0"},
		{"v5 scoped underscore", "lockfileVersion: 5.4\n\npackages:\n\n  /@scope/pkg/1.0.0_bar@2.0.0:\n    dev: false\n", "@scope/pkg", "1.0.0"},
		{"v6 parenthesis", "lockfileVersion: '6.0'\n\npackages:\n\n  /react-dom@18.2.0(react@18.2.0):\n    dev: false\n", "react-dom", "18.2.0"},
		{"v9 parenthesis", "lockfileVersion: '9.0'\n\npackages:\n\n  react-dom@18.2.0(react@18.2.0):\n    resolution: {}\n", "react-dom", "18.2.0"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			pkgs, err := parsePnpmLock([]byte(tc.input))
			if err != nil {
				t.Fatalf("parsePnpmLock: %v", err)
			}
			if len(pkgs) != 1 {
				t.Fatalf("expected 1 package, got %d: %+v", len(pkgs), pkgs)
			}
			if pkgs[0].Name != tc.wantName || pkgs[0].Version != tc.wantVersion {
				t.Errorf("got %q@%q, want %q@%q",
					pkgs[0].Name, pkgs[0].Version, tc.wantName, tc.wantVersion)
			}
		})
	}
}

// TestParseYarnLock_BerryProtocols covers berry descriptors whose RANGE itself
// contains an '@'. Splitting on the last '@' then eats part of the range into
// the name. The alias form is not exotic — cliui and wrap-ansi put it in
// essentially every modern berry lockfile.
func TestParseYarnLock_BerryProtocols(t *testing.T) {
	t.Parallel()

	for _, tc := range []struct{ name, input, want string }{
		{"npm alias", "\"string-width-cjs@npm:string-width@^4.2.0\":\n  version: 4.2.3\n", "string-width-cjs"},
		{"patch protocol", "\"lodash@patch:lodash@npm%3A4.17.21#~/.yarn/patch.diff\":\n  version: 4.17.21\n", "lodash"},
		{"plain npm protocol", "\"lodash@npm:^4.17.15\":\n  version: 4.17.21\n", "lodash"},
		{"scoped alias", "\"@foo/bar@npm:@baz/qux@^1.0.0\":\n  version: 1.2.3\n", "@foo/bar"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			pkgs, err := parseYarnLock([]byte(tc.input))
			if err != nil {
				t.Fatalf("parseYarnLock: %v", err)
			}
			if len(pkgs) != 1 {
				t.Fatalf("expected 1 package, got %d: %+v", len(pkgs), pkgs)
			}
			if pkgs[0].Name != tc.want {
				t.Errorf("name = %q, want %q", pkgs[0].Name, tc.want)
			}
		})
	}
}

// TestParseYarnLock_CommaInsideRange guards against phantom packages. A
// descriptor may carry a comma INSIDE one range ("foo@>=1.0.0, <2.0.0"), and
// splitting on every comma turns the fragment "<2.0.0" into a package of that
// name — polluting the inventory and the SBOM with entries that do not exist.
func TestParseYarnLock_CommaInsideRange(t *testing.T) {
	t.Parallel()

	pkgs, err := parseYarnLock([]byte("\"foo@>=1.0.0, <2.0.0\":\n  version \"1.5.0\"\n"))
	if err != nil {
		t.Fatalf("parseYarnLock: %v", err)
	}
	if len(pkgs) != 1 {
		t.Fatalf("expected 1 package, got %d: %+v", len(pkgs), pkgs)
	}
	if pkgs[0].Name != "foo" {
		t.Errorf("name = %q, want foo", pkgs[0].Name)
	}
}

// TestParsers_AgainstRealLockfiles runs each parser over a lockfile trimmed
// from a real project rather than written for the test.
//
// Every parser bug this suite has caught came from a shape nobody thought to
// invent: yarn's npm-alias protocol, pnpm's peer suffixes, poetry's nested
// tables. A fixture the parser's author writes tends to match the parser they
// wrote. See testdata/lockfiles/SOURCES.md for provenance.
func TestParsers_AgainstRealLockfiles(t *testing.T) {
	t.Parallel()

	for _, tc := range []struct {
		file      string
		parse     func([]byte) ([]Package, error)
		ecosystem string
		minPkgs   int
	}{
		{"yarn-v1/yarn.lock", parseYarnLock, "npm", 20},
		{"pnpm-v6/pnpm-lock.yaml", parsePnpmLock, "npm", 10},
		{"poetry/poetry.lock", parsePoetryLock, "pypi", 5},
	} {
		t.Run(tc.file, func(t *testing.T) {
			t.Parallel()

			data, err := os.ReadFile(filepath.Join("testdata", "lockfiles", tc.file))
			if err != nil {
				t.Fatalf("reading fixture: %v", err)
			}

			pkgs, err := tc.parse(data)
			if err != nil {
				t.Fatalf("parse: %v", err)
			}
			if len(pkgs) < tc.minPkgs {
				t.Fatalf("parsed %d packages, expected at least %d — the parser is "+
					"silently reading almost nothing from a real file", len(pkgs), tc.minPkgs)
			}

			for _, p := range pkgs {
				if p.Name == "" {
					t.Errorf("package with empty name: %+v", p)
				}
				if p.Ecosystem != tc.ecosystem {
					t.Errorf("%s: ecosystem %q, want %q", p.Name, p.Ecosystem, tc.ecosystem)
				}
				// A version must be concrete. A range or protocol here means
				// the descriptor was read instead of the resolution, which
				// matches no advisory and fails every lookup silently.
				if p.Version == "" || strings.ContainsAny(p.Version, "^~><*| ") || strings.Contains(p.Version, ":") {
					t.Errorf("%s has %q, which is not a concrete version", p.Name, p.Version)
				}
				// Name corruption from a mishandled separator.
				if strings.ContainsAny(p.Name, "()") || strings.Contains(p.Name, "npm:") {
					t.Errorf("%s: name carries range or protocol syntax", p.Name)
				}
			}
			t.Logf("%s -> %d packages", tc.file, len(pkgs))
		})
	}
}
