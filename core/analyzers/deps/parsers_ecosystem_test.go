// Fixtures below are trimmed from real lockfiles rather than invented, because
// the failure these parsers exist to fix was a format nox recognised but could
// not read. A hand-shaped fixture that happens to match the parser proves
// nothing about the files users actually have.

// --- yarn ---

// yarn v1 uses a bespoke, indentation-based format: a descriptor line listing
// one or more range specs, then an indented `version` line. The descriptor is
// not the resolved version, which is the trap — "lodash@^4.17.0" is a range.
const yarnV1Lock = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


lodash@^4.17.0, lodash@^4.17.15:
  version "4.17.20"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.20.tgz#b44a9b6297bcb698f1c51a3545a2b3b368d59c52"
  integrity sha512-PlhdFcillOINfeV7Ni6oF1TAEayyZBoZ8bcshTHqOYJYlrqzRK5hagpagky5o4HfCzzd1TRkXPMFq6cKk9rGmA==

"@babel/core@^7.0.0":
  version "7.22.5"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.22.5.tgz"
  integrity sha512-abc==

express@4.18.2:
  version "4.18.2"
  resolved "https://registry.yarnpkg.com/express/-/express-4.18.2.tgz"
`

// yarn berry (v2+) switched to YAML with a __metadata block that must not be
// mistaken for a package.
const yarnBerryLock = `# This file is generated by running "yarn install" inside your project.

__metadata:
  version: 6
  cacheKey: 8

"lodash@npm:^4.17.15":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  checksum: eb835a2e51d381e561e508ce932ea50a8e5a68f
  languageName: node
  linkType: hard

"express@npm:4.18.2":
  version: 4.18.2
  resolution: "express@npm:4.18.2"
  languageName: node
  linkType: hard
`

func TestParseYarnLock_V1(t *testing.T) {
	t.Parallel()

	pkgs, err := parseYarnLock([]byte(yarnV1Lock))
	if err != nil {
		t.Fatalf("parseYarnLock: %v", err)
	}

	want := map[string]string{
		"lodash":      "4.17.20",
		"@babel/core": "7.22.5",
		"express":     "4.18.2",
	}
	assertPackages(t, pkgs, want, "npm")
}

func TestParseYarnLock_Berry(t *testing.T) {
	t.Parallel()

	pkgs, err := parseYarnLock([]byte(yarnBerryLock))
	if err != nil {
		t.Fatalf("parseYarnLock: %v", err)
	}

	assertPackages(t, pkgs, map[string]string{
		"lodash":  "4.17.21",
		"express": "4.18.2",
	}, "npm")

	for _, p := range pkgs {
		if p.Name == "__metadata" {
			t.Error("the berry __metadata block was parsed as a package")
		}
	}
}

func TestParseYarnLock_ResolvesRangeToConcreteVersion(t *testing.T) {
	t.Parallel()

	// The descriptor carries a range; only the version line is authoritative.
	// Reading the descriptor would report "^4.17.0", which matches no advisory
	// and silently fails every OSV lookup.
	pkgs, err := parseYarnLock([]byte(yarnV1Lock))
	if err != nil {
		t.Fatalf("parseYarnLock: %v", err)
	}
	for _, p := range pkgs {
		if p.Version == "" || p.Version[0] == '^' || p.Version[0] == '~' {
			t.Errorf("%s resolved to a range %q rather than a concrete version", p.Name, p.Version)
		}
	}
}

