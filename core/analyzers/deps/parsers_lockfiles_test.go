package deps

import (
	"sort"
	"testing"
)

func namesVersions(t *testing.T, pkgs []Package, eco string) []string {
	t.Helper()
	var out []string
	for _, p := range pkgs {
		if p.Ecosystem != eco {
			t.Errorf("package %s has ecosystem %q, want %q", p.Name, p.Ecosystem, eco)
		}
		out = append(out, p.Name+"@"+p.Version)
	}
	sort.Strings(out)
	return out
}

func equalStrings(t *testing.T, got, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for i := range got {
		if got[i] != want[i] {
			t.Fatalf("got %v, want %v", got, want)
		}
	}
}

// Shaped like pipenv's output: hashes, markers, a VCS dependency with a ref
// and no version, and a develop section that is a dependency all the same.
func TestParsePipfileLock(t *testing.T) {
	content := []byte(`{
    "_meta": {"hash": {"sha256": "abc"}, "pipfile-spec": 6, "requires": {},
              "sources": [{"name": "pypi", "url": "https://pypi.org/simple", "verify_ssl": true}]},
    "default": {
        "requests": {"hashes": ["sha256:1"], "index": "pypi", "markers": "python_version >= '3.8'", "version": "==2.25.1"},
        "urllib3": {"hashes": ["sha256:2"], "version": "==1.26.5"},
        "mylib": {"git": "https://github.com/example/mylib.git", "ref": "deadbeef"}
    },
    "develop": {
        "pytest": {"hashes": ["sha256:3"], "version": "==7.0.0"}
    }
}`)
	pkgs, err := parsePipfileLock(content)
	if err != nil {
		t.Fatal(err)
	}
	equalStrings(t, namesVersions(t, pkgs, "pypi"), []string{"pytest@7.0.0", "requests@2.25.1", "urllib3@1.26.5"})

	if _, err := parsePipfileLock([]byte("{not json")); err == nil {
		t.Fatal("malformed Pipfile.lock must error, not yield an empty inventory")
	}
}

// Shaped like uv's output: the project itself is an editable source and is
// not a dependency; registry packages carry an index URL; a directory
// dependency is a workspace member.
func TestParseUvLock(t *testing.T) {
	content := []byte(`version = 1
requires-python = ">=3.9"

[[package]]
name = "anyio"
version = "4.4.0"
source = { registry = "https://pypi.org/simple" }
dependencies = [
    { name = "idna" },
]
sdist = { url = "https://files.pythonhosted.org/anyio-4.4.0.tar.gz", hash = "sha256:1" }

[[package]]
name = "idna"
version = "3.7"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "myproject"
version = "0.1.0"
source = { editable = "." }
dependencies = [
    { name = "anyio" },
]

[package.metadata]
requires-dist = [{ name = "anyio", specifier = ">=4" }]

[[package]]
name = "member"
version = "0.0.1"
source = { directory = "packages/member" }
`)
	pkgs, err := parseUvLock(content)
	if err != nil {
		t.Fatal(err)
	}
	equalStrings(t, namesVersions(t, pkgs, "pypi"), []string{"anyio@4.4.0", "idna@3.7"})
}

// Shaped like pub's output: hosted packages with a description block, an sdk
// package, a path package and a git package, then the sdks trailer.
func TestParsePubspecLock(t *testing.T) {
	content := []byte(`# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
  async:
    dependency: transitive
    description:
      name: async
      sha256: "947bfcf1"
      url: "https://pub.dev"
    source: hosted
    version: "2.11.0"
  dio:
    dependency: "direct main"
    description:
      name: dio
      sha256: "0dfb6b6a"
      url: "https://pub.dev"
    source: hosted
    version: "4.0.0"
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
  local_widgets:
    dependency: "direct main"
    description:
      path: "../local_widgets"
      relative: true
    source: path
    version: "1.0.0"
  fancy:
    dependency: "direct main"
    description:
      path: "."
      ref: main
      resolved-ref: abc123
      url: "https://github.com/example/fancy.git"
    source: git
    version: "2.0.0"
sdks:
  dart: ">=3.0.0 <4.0.0"
  flutter: ">=3.10.0"
`)
	pkgs, err := parsePubspecLock(content)
	if err != nil {
		t.Fatal(err)
	}
	equalStrings(t, namesVersions(t, pkgs, "pub"), []string{"async@2.11.0", "dio@4.0.0"})
}

