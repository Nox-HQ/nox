// Package annotate builds GitHub PR review payloads from security findings.
// The payload construction lives here so both CLI and MCP can use it;
// the actual GitHub API call remains in the CLI layer.
package annotate

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/nox-hq/nox/core/findings"
)

// ReviewComment is a single line-level comment on a PR.
type ReviewComment struct {
	Path string `json:"path"`
	Line int    `json:"line,omitempty"`
	Body string `json:"body"`
	Side string `json:"side"`
}

// ReviewPayload is the full PR review request body.
type ReviewPayload struct {
	Event    string          `json:"event"`
	Body     string          `json:"body"`
	Comments []ReviewComment `json:"comments"`
}

// BuildReviewPayload constructs a GitHub PR review payload from findings.
func BuildReviewPayload(ff []findings.Finding) *ReviewPayload {
	if len(ff) == 0 {
		return nil
	}

	var comments []ReviewComment
	for i := range ff {
		badge := SeverityBadge(ff[i].Severity)
		// %#q rather than a literal backquote pair around %s. The two are
		// identical for every rule ID nox issues -- they match `[A-Z]+-[0-9]+`,
		// so %#q always picks the backquoted form -- and
		// TestBuildReviewPayload_Body pins the rendered string so the
		// equivalence is checked rather than assumed. %#q would differ only for a
		// value containing a backquote or a newline, which a rule ID cannot.
		body := fmt.Sprintf("%s **%s** %#q\n\n%s", badge, ff[i].Severity, ff[i].RuleID, ff[i].Message)

		c := ReviewComment{
			Path: ff[i].Location.FilePath,
			Body: body,
			Side: "RIGHT",
		}
		if ff[i].Location.StartLine > 0 {
			c.Line = ff[i].Location.StartLine
		}
		comments = append(comments, c)
	}

	return &ReviewPayload{
		Event:    "COMMENT",
		Body:     fmt.Sprintf("Nox found **%d finding(s)** in this PR.", len(ff)),
		Comments: comments,
	}
}

// SeverityBadge returns a GitHub-flavored emoji badge for the given severity.
func SeverityBadge(sev findings.Severity) string {
	switch sev {
	case findings.SeverityCritical:
		return ":red_circle:"
	case findings.SeverityHigh:
		return ":orange_circle:"
	case findings.SeverityMedium:
		return ":yellow_circle:"
	case findings.SeverityLow:
		return ":large_blue_circle:"
	default:
		return ":white_circle:"
	}
}

// Options bound what is posted inline. The zero value posts every finding,
// as annotate always has.
type Options struct {
	// MaxComments caps the inline comments; 0 is no cap. Under a cap the
	// most severe findings are the ones posted.
	MaxComments int
	// MinSeverity drops findings below it; "" keeps every severity.
	MinSeverity findings.Severity
}

// Select returns the findings to post inline under o.
func Select(ff []findings.Finding, o Options) []findings.Finding {
	out := make([]findings.Finding, 0, len(ff))
	for i := range ff {
		if o.MinSeverity == "" || findings.SeverityRank(ff[i].Severity) <= findings.SeverityRank(o.MinSeverity) {
			out = append(out, ff[i])
		}
	}
	if o.MaxComments > 0 && len(out) > o.MaxComments {
		sort.SliceStable(out, func(i, j int) bool {
			return findings.SeverityRank(out[i].Severity) < findings.SeverityRank(out[j].Severity)
		})
		out = out[:o.MaxComments]
	}
	return out
}

// Summary is the PR comment that counts every finding in the report by
// severity, and says how many were posted inline and under what bounds.
func Summary(all []findings.Finding, posted int, o Options) string {
	counts := map[findings.Severity]int{}
	for i := range all {
		counts[all[i].Severity]++
	}
	limit, floor := "none", "any"
	if o.MaxComments > 0 {
		limit = strconv.Itoa(o.MaxComments)
	}
	if o.MinSeverity != "" {
		floor = string(o.MinSeverity)
	}
	var b strings.Builder
	b.WriteString("## Nox Security Scan Summary\n\n| Severity | Count |\n|----------|-------|\n")
	for _, r := range []struct {
		sev   findings.Severity
		label string
	}{
		{findings.SeverityCritical, "Critical"},
		{findings.SeverityHigh, "High"},
		{findings.SeverityMedium, "Medium"},
		{findings.SeverityLow, "Low"},
		{findings.SeverityInfo, "Info"},
	} {
		fmt.Fprintf(&b, "| %s %s | %d |\n", SeverityBadge(r.sev), r.label, counts[r.sev])
	}
	fmt.Fprintf(&b, "| **Total** | **%d** |\n\n", len(all))
	fmt.Fprintf(&b, "%d inline comment(s) posted (max: %s, min severity: %s).\n\n", posted, limit, floor)
	b.WriteString("---\n<sub>Generated by [nox](https://github.com/nox-hq/nox) security scanner</sub>\n")
	return b.String()
}
