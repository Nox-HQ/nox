package core

import (
	"context"
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/nox-hq/nox/core/analyzers/agentflow"
	"github.com/nox-hq/nox/core/analyzers/taintflow"
	"github.com/nox-hq/nox/core/discovery"
	"github.com/nox-hq/nox/core/findings"
)

// One walk serving both flow analyzers must report exactly what each reports
// running on its own: the same findings, in the same order, from each.
func TestFlowsTogetherReportWhatEachReportsAlone(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"app.py": `def handler():
    q = request.args.get("q")
    os.system(q)
    openai.chat.completions.create(messages=[{"role": "user", "content": q}])
`,
		"b/agent.py": `def run():
    out = client.messages.create(model="claude", messages=[])
    os.system(out)
`,
		"web/x.js": `app.get("/", (req, res) => { eval(req.query.code) })
`,
		"gen.py": "# Code generated by tool. DO NOT EDIT.\nimport os\nos.system(request.args.get(\"c\"))\n",

		"README.md": "os.system(request.args.get('c'))\n",
	}
	var arts []discovery.Artifact
	for name, content := range files {
		abs := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(abs, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		typ := discovery.Source
		if name == "README.md" {
			typ = discovery.Unknown
		}
		arts = append(arts, discovery.Artifact{Path: name, AbsPath: abs, Type: typ})
	}

	ctx := context.Background()
	taintAlone, err := taintflow.NewAnalyzer().ScanArtifacts(ctx, arts)
	if err != nil {
		t.Fatal(err)
	}
	agentAlone, err := agentflow.NewAnalyzer().ScanArtifacts(ctx, arts)
	if err != nil {
		t.Fatal(err)
	}
	if len(taintAlone.Findings()) == 0 || len(agentAlone.Findings()) == 0 {
		t.Fatalf("test premise: both analyzers find something (taint %d, agent %d)",
			len(taintAlone.Findings()), len(agentAlone.Findings()))
	}

	var together []*findings.FindingSet
	err = scanFlowsTogether(ctx, arts, taintflow.NewAnalyzer(), agentflow.NewAnalyzer(), func(fs *findings.FindingSet) {
		together = append(together, fs)
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(together) != 2 {
		t.Fatalf("got %d finding sets, want 2", len(together))
	}
	if got, want := together[0].Findings(), taintAlone.Findings(); !reflect.DeepEqual(got, want) {
		t.Errorf("taintflow together:\n%+v\nalone:\n%+v", got, want)
	}
	if got, want := together[1].Findings(), agentAlone.Findings(); !reflect.DeepEqual(got, want) {
		t.Errorf("agentflow together:\n%+v\nalone:\n%+v", got, want)
	}
}
