#!/usr/bin/env bash
# Renders the Homebrew cask for a release, byte-for-byte what GoReleaser
# (homebrew_casks in .goreleaser.yaml, pinned in release.yml) emits.
#
# Usage: render-homebrew-cask.sh <tag> <checksums.txt> [version]
#   tag        release tag used in download URLs (e.g. v1.54.0)
#   checksums  GoReleaser checksums.txt for that release
#   version    defaults to the tag without its leading "v"
#
# Used by .github/workflows/publish-homebrew.yml and runnable locally to diff
# against a `goreleaser release --snapshot` cask. If GoReleaser's cask template
# changes (e.g. on a version bump), update this script with it.
set -euo pipefail

tag="${1:?tag required}"
checksums="${2:?checksums.txt required}"
version="${3:-${tag#v}}"
base="https://github.com/nox-hq/nox/releases/download/${tag}"

sha_for() {
  local f="nox_${version}_$1.tar.gz" h
  h=$(grep -E "  ${f}\$" "$checksums" | awk '{print $1}')
  if [ -z "$h" ]; then
    echo "::error::${f} is not listed in checksums.txt" >&2
    exit 1
  fi
  printf '%s' "$h"
}

block() { # os arch-kind arch
  echo "    on_$2 do"
  echo "      sha256 \"$(sha_for "$1_$3")\""
  echo "      url \"${base}/nox_#{version}_$1_$3.tar.gz\""
  echo "    end"
}

echo '# This file was generated by GoReleaser. DO NOT EDIT.'
echo 'cask "nox" do'
echo "  version \"${version}\""
echo ''
for os in macos linux; do
  goos=${os/macos/darwin}
  echo "  on_${os} do"
  block "$goos" arm arm64
  block "$goos" intel amd64
  echo '  end'
done
cat <<'EOF'

  name "nox"
  desc "Language-agnostic security scanner with first-class AI application security"
  homepage "https://github.com/nox-hq/nox"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "nox"

  postflight_steps do
    on_macos do
      run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{staged_path}}/nox"]
    end
  end

  # No zap stanza required
end
EOF
