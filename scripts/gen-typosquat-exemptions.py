#!/usr/bin/env python3
"""Regenerate the VULN-002 (typosquatting) exemption sets.

VULN-002 compares a dependency name against a small curated list of TARGETS,
the packages attackers imitate (core/analyzers/deps/data/popular_*.txt). Those
lists used to be the only exemption as well, so an established package outside
roughly 240 hand-picked names that sat one edit from a target was reported as a
typosquat: openai (openapi), jws (ws), safer-buffer (safe-buffer).

The exemption is now a much larger set of established packages per ecosystem,
taken from a published ranking and embedded as a pinned data file. This script
is the only thing that touches the network; a scan never does. Each source is
pinned by version or tag and by the sha256 of the downloaded bytes, so a rerun
either reproduces the committed files exactly or fails loudly.

Names listed in known_malicious.json (VULN-003) are removed from the output:
a known-malicious package is never exempt, however popular it became. The Go
side enforces the same rule at scan time and a test checks the files.

To refresh: bump the pins below (version/tag, sha256, retrieval date), run

    python3 scripts/gen-typosquat-exemptions.py

and review the diff of core/analyzers/deps/data/established_*.txt. The names
that matter are the ones one edit from a target, since those are the only ones
the exemption changes a verdict for; --neighbors lists them. Check each new one
is a real project before committing: a ranking built from download and
dependent counts can be inflated.

Usage: gen-typosquat-exemptions.py [--check] [--neighbors]
  --check      regenerate in memory and exit 1 if the committed files differ.
  --neighbors  print each exempted name that is one edit from a target.
"""

import hashlib
import io
import json
import os
import re
import sys
import tarfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "core", "analyzers", "deps", "data")

RETRIEVED = "2026-10-24"

NPM = {
    "name": "npm-high-impact 1.13.0",
    "url": "https://registry.npmjs.org/npm-high-impact/-/npm-high-impact-1.13.0.tgz",
    "sha256": "63ed31dacc861ac10c95b47af242a984f210f0170eaea8eaa66ba4a9b8f9d30b",
    "member": "package/lib/top.js",
    "license": "MIT, Copyright (c) Titus Wormer (https://github.com/wooorm/npm-high-impact)",
    "selection": (
        "every name in lib/top.js: the packages npm itself classifies as high-impact "
        "(1,000,000+ weekly downloads or 500+ dependents)"
    ),
    "limit": None,
    "out": "established_npm.txt",
}

PYPI = {
    "name": "hugovk/top-pypi-packages release 2026.10.1 (30-day downloads, data as of 2026-10-01)",
    "url": "https://raw.githubusercontent.com/hugovk/top-pypi-packages/2026.10.1/top-pypi-packages.min.json",
    "sha256": "55fee05ed02b628f05350a51780ec436efae39ea0810df5d5419e15b850c7041",
    "license": (
        "CC-BY-4.0 as recorded on Zenodo (https://zenodo.org/records/23082845); "
        "the GitHub repository carries no license file. Data: the public ClickHouse PyPI downloads dataset"
    ),
    "selection": "the 10,000 most-downloaded projects (about 125,000+ downloads in the 30 days)",
    "limit": 10000,
    "out": "established_pypi.txt",
}


def fetch(url, sha256):
    with urllib.request.urlopen(url, timeout=60) as resp:  # noqa: S310 - pinned https URL
        body = resp.read()
    got = hashlib.sha256(body).hexdigest()
    if got != sha256:
        sys.exit(f"sha256 mismatch for {url}: got {got}, pinned {sha256}")
    return body


def npm_names(src):
    body = fetch(src["url"], src["sha256"])
    with tarfile.open(fileobj=io.BytesIO(body), mode="r:gz") as tar:
        member = tar.extractfile(src["member"])
        if member is None:
            sys.exit(f"{src['member']} missing from {src['url']}")
        text = member.read().decode("utf-8")
    return re.findall(r"'([^'\s]+)'", text)


def pypi_names(src):
    rows = json.loads(fetch(src["url"], src["sha256"]))["rows"]
    return [row["project"] for row in rows]


def normalize(name):
    """PEP 503 canonical form; matches normalizeDistName in malicious.go."""
    return re.sub(r"[-_.]+", "-", name.lower()).strip("-")


def render(eco, src, names, malicious):
    if src["limit"] is not None:
        names = names[: src["limit"]]
    bad = {normalize(n) for n in malicious.get(eco, [])}
    kept = sorted({normalize(n) for n in names} - bad)
    dropped = sorted({normalize(n) for n in names} & bad)
    header = [
        f"# Established {eco} packages: names exempt from VULN-002 (typosquatting).",
        "# A name listed here is never reported as a typosquat of another package,",
        "# unless it is also in known_malicious.json (malicious always wins).",
        "#",
        "# GENERATED by scripts/gen-typosquat-exemptions.py; do not edit by hand.",
        f"# Source: {src['name']}",
        f"# URL: {src['url']}",
        f"# sha256: {src['sha256']}",
        f"# License: {src['license']}",
        f"# Retrieved: {RETRIEVED}",
        f"# Selection: {src['selection']}; PEP 503 normalized, sorted.",
        f"# Removed as known-malicious: {', '.join(dropped) if dropped else 'none'}",
        f"# Count: {len(kept)}",
    ]
    return "\n".join(header + kept) + "\n"


def one_edit(a, b):
    """True when a and b are exactly one insertion, deletion or substitution apart."""
    if a == b or abs(len(a) - len(b)) > 1:
        return False
    if len(a) > len(b):
        a, b = b, a
    i = 0
    while i < len(a) and a[i] == b[i]:
        i += 1
    if len(a) == len(b):
        return a[i + 1 :] == b[i + 1 :]
    return a[i:] == b[i + 1 :]


def print_neighbors(eco, text):
    with open(os.path.join(DATA, f"popular_{eco}.txt"), encoding="utf-8") as f:
        targets = {normalize(l.strip()) for l in f if l.strip() and not l.startswith("#")}
    for name in (l for l in text.splitlines() if not l.startswith("#")):
        if name in targets:
            continue
        near = sorted(t for t in targets if one_edit(name, t))
        if near:
            print(f"{eco}: {name} ~ {', '.join(near)}")


def main():
    check = "--check" in sys.argv[1:]
    with open(os.path.join(DATA, "known_malicious.json"), encoding="utf-8") as f:
        malicious = json.load(f)
    outputs = {
        NPM["out"]: render("npm", NPM, npm_names(NPM), malicious),
        PYPI["out"]: render("pypi", PYPI, pypi_names(PYPI), malicious),
    }
    if "--neighbors" in sys.argv[1:]:
        print_neighbors("npm", outputs[NPM["out"]])
        print_neighbors("pypi", outputs[PYPI["out"]])
    stale = []
    for name, text in outputs.items():
        path = os.path.join(DATA, name)
        if check:
            try:
                with open(path, encoding="utf-8") as f:
                    if f.read() != text:
                        stale.append(name)
            except FileNotFoundError:
                stale.append(name)
            continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {path}")
    if stale:
        sys.exit(f"stale: {', '.join(stale)}")


if __name__ == "__main__":
    main()
